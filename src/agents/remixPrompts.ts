export function buildRemixSystemPrompt(
  brandContext?: string,
  marketFindings?: string,
  pastFeedback?: string,
): SystemBlock[] {
  // 캐시되는 고정부(유튜브 기획 지식 베이스) — 호출마다 동일.
  const staticText = `당신은 유튜브 대본 기획자입니다.

${YOUTUBE_KNOWLEDGE}

${THREAD_EBOOK_FOR_YOUTUBE}

[대표님 스레드 전자책 원문 노하우 — "광고비 0원으로 고객이 먼저 연락오는 스레드 마케팅" (유튜브 대본에도 그대로 적용)]
아래는 스레드 위원회가 쓰는 것과 "동일한" 전자책 노하우다. 이미 내장되어 있으니 대표님께 내용을 따로 요청하지 말고,
훅·스토리 구조·고객 중심·CTA·판매 심리 원리를 유튜브 제목·초반 후킹·6단계 대본에 응용한다(스레드 표현은 유튜브 구어체로 리라이팅).
${THREAD_KNOWLEDGE}

${PAID_THREAD_KNOWLEDGE}

주어진 자료(주제, 참고 텍스트)를 바탕으로 유튜브 영상 기획안을 만드세요. 촬영·편집은 하지 않고 기획안까지만 작성합니다.
채점 기준(제목 클릭력·썸네일 방향성·초반 후킹·정보형 6단계·알고리즘 시청지속·마잘남 정체성, 합계 100점, 통과 90점)을
스스로 통과하도록 처음부터 완성도 높게 쓴다 — 미달이면 다시 써야 하니 한 번에 잘 만든다.

규칙:
1. 위 지식 베이스와 카피라이팅 원리, (제공된 경우) 브레인 리서치 자료를 근거로 기획한다. 직접 웹 검색은 하지 않는다 —
   최신 벤치마킹·트렌드가 필요하면 브레인이 조사해둔 자료를 활용하고, 그게 없으면 지식 베이스 방법론으로 기획한다.
2. title: 최종 추천 영상 제목 1개(가장 강한 것 하나로 확정). 반드시 채운다 — 비워두지 말 것.
   "혜택 있는 의문형"(내용이 다 추측되면 안 됨, 시청자 머릿속에 물음표를 만드는 문장), 타깃 키워드를 제목 앞에 배치. 클릭할 이유가 분명해야 한다.
3. hooks: 제목 후보 3개(title 외 대안). 각각 "혜택 있는 의문형", 타깃 키워드를 앞에 배치. title은 이 중 가장 강한 것이거나 이를 다듬은 것.
4. outline: 정보형 6단계(유인·문제제기 → 공감 예시 → 해결+보상 → 행동유도 → 암시·독려 → 기대·다음영상)를 따라 대본 흐름을 단락별로 작성. 초반 1분 안에 공감·문제해결 신호가 반드시 들어가고, "한 사람에게 말 걸듯" 구어체로 쓴다.
   ★ 각 단계는 2~4문장으로 간결하게 쓴다(전체 기획안이 너무 길어져 응답이 잘리지 않게 — 대본 전체가 아니라 단계별 핵심 흐름·포인트만).
5. benchmarkNotes: (브레인 리서치가 제공된 경우 그 자료 기반으로) "구독자 적은데 떡상한(퍼스트 히트) 영상"의 제목·썸네일 범주(기대/증거/의문/공감)·왜 먹히는지 벤치마킹 포인트를 구체적으로 나열. 대형 채널·광고 의심·시즌성 지난 것은 제외.
6. 반드시 아래 JSON 스키마와 정확히 일치하는 JSON만 출력한다. 설명이나 마크다운 코드블록 없이 최종 답변은 순수 JSON만 출력한다.

JSON 스키마:
{
  "title": string,
  "hooks": [ string ],
  "outline": string,
  "benchmarkNotes": [ string ]
}`

  // 캐시 안 되는 변동부 — 브랜드·시장 리서치·지난 성과 피드백.
  const brandBlock = brandContext ? `[브랜드]\n${brandContext}` : ''
  const marketBlock = marketFindings
    ? `[브레인이 조사한 최근 시장 리서치 — 참고해서 방향성에 반영]\n${marketFindings}`
    : ''
  // 새 영상이 올라오면 레이더가 성과를 분석해 저장해둔 피드백 — 다음 기획을
  // 실제 성과에 맞춰 디벨롭한다(잘 된 요소 강화, 약했던 부분 보완).
  const feedbackBlock = pastFeedback
    ? `[지난 유튜브 성과 피드백 — 반드시 반영해 다음 기획을 개선]\n${pastFeedback}`
    : ''
  const dynamicText = [brandBlock, marketBlock, feedbackBlock].filter(Boolean).join('\n\n')

  return cachedSystem(staticText, dynamicText)
}

export function buildRemixUserPrompt(params: {
  topic: string
  referenceText: string
  previousPlan?: { title: string; outline: string }
  feedback?: string
}): string {
  const { topic, referenceText, previousPlan, feedback } = params
  // 채점 미달로 재작성할 때 — 이전 기획안 + 심사 피드백을 붙여서 그 부분을
  // 반영해 다시 쓰게 한다(한 번만 재작성).
  const revisionBlock =
    previousPlan && feedback
      ? `\n\n[이전 기획안 — 채점 미달]\n제목: ${previousPlan.title}\n구성: ${previousPlan.outline}\n\n[채점관 피드백 — 이 약점을 반드시 고쳐서 다시 작성]\n${feedback}`
      : ''
  return `[주제]
${topic}

[참고 자료]
${referenceText || '(제공되지 않음 — 지식 베이스 기준으로 기획)'}${revisionBlock}

위 내용으로 유튜브 기획안을 작성하고 JSON으로만 답하세요.`
}
